<?php

declare(strict_types=1);

namespace Ims\Agent;

/**
 * Paths and identity persistence.
 *
 * config/identity.php is a PHP file returning an array. It starts with a guard
 * so it outputs nothing even if it were ever requested through a web server,
 * and it is written with 0600 permissions inside a 0700 directory that also
 * carries a deny-all .htaccess.
 */
final class Config
{
    /** @var string */
    public $root;
    /** @var string */
    public $configDir;
    /** @var string */
    public $stateDir;
    /** @var string */
    public $logFile;
    /** @var string */
    public $defaultBackupDir;

    public function __construct(?string $root = null)
    {
        $this->root = $root ?? IMS_AGENT_ROOT;
        $this->configDir = $this->root . '/config';
        $this->stateDir = $this->root . '/state';
        $this->logFile = $this->root . '/logs/agent.log';
        $home = getenv('HOME') ?: dirname($this->root);
        $this->defaultBackupDir = rtrim($home, '/') . '/ims-backups';
    }

    public function identityFile(): string
    {
        return $this->configDir . '/identity.php';
    }

    public function statePath(string $name): string
    {
        return $this->stateDir . '/' . $name;
    }

    public function ensureDirectories(): void
    {
        foreach ([$this->configDir, $this->stateDir, dirname($this->logFile)] as $dir) {
            if (!is_dir($dir) && !mkdir($dir, 0700, true) && !is_dir($dir)) {
                throw new \RuntimeException("Cannot create directory {$dir}");
            }
            @chmod($dir, 0700);
            $htaccess = $dir . '/.htaccess';
            if (!is_file($htaccess)) {
                file_put_contents($htaccess, "Require all denied\nDeny from all\n");
            }
        }
    }

    /** @return array<string,string>|null */
    public function loadIdentity(): ?array
    {
        $file = $this->identityFile();
        if (!is_file($file)) {
            return null;
        }
        if (DIRECTORY_SEPARATOR === '/' && (fileperms($file) & 0077) !== 0) {
            throw new \RuntimeException("{$file} must not be readable by group/others (chmod 600)");
        }
        $identity = (static function (string $f) {
            return require $f;
        })($file);
        if (!is_array($identity) || empty($identity['nodeId']) || empty($identity['nodeSecret']) || empty($identity['coreUrl'])) {
            throw new \RuntimeException('Identity file is invalid');
        }
        return $identity;
    }

    /** @param array<string,string|null> $identity */
    public function saveIdentity(array $identity): void
    {
        $this->ensureDirectories();
        $php = "<?php\n// IMS cPanel Agent identity - generated by register.php. Keep private.\n"
            . "defined('IMS_AGENT') || exit;\nreturn " . var_export($identity, true) . ";\n";
        Fs::writeAtomic($this->identityFile(), $php);
    }
}
